import { z } from "zod";
import { describeCriteria, INDIVIDUAL, INDIVIDUAL_INFO, SET, SET_INFO } from "./criteria.ts";
import type { Prompt } from "./llm.ts";

const Severity = z.enum(["high", "medium", "low"]);

export const ExtractSchema = z.object({
  title: z.string().describe("Название документа, как оно написано в документе"),
  requirements: z.array(
    z.object({
      doc_id: z.string().nullable().describe("Идентификатор в документе (например «Ф-1»), null если номера нет"),
      section: z.string().describe("Раздел документа, путь заголовков через « / »"),
      type: z.enum(["functional", "nonfunctional", "data", "integration", "interface", "ui", "acceptance", "other"]),
      summary: z.string().describe("Краткая формулировка требования, до 20 слов"),
      quote: z.string().describe("Дословная цитата требования из документа"),
    }),
  ),
});

export const CheckSchema = z.object({
  results: z.array(
    z.object({
      req_id: z.string(),
      findings: z.array(
        z.object({
          criterion: z.enum(INDIVIDUAL),
          severity: Severity,
          quote: z.string().describe("Дословный фрагмент документа, в котором дефект"),
          problem: z.string().describe("В чём нарушение, со ссылкой на текст"),
          fix: z.string().describe("Как переформулировать или что добавить"),
          question: z.string().describe("Уточняющий вопрос автору документа, ответ на который снимает дефект"),
        }),
      ),
    }),
  ),
});

export const SetSchema = z.object({
  findings: z.array(
    z.object({
      criterion: z.enum(SET),
      severity: Severity,
      req_ids: z.array(z.string()).describe("Затронутые требования (ID из отчёта)"),
      quotes: z.array(z.string()).min(1).describe("Дословные фрагменты документа; для противоречия — оба места"),
      problem: z.string(),
      fix: z.string(),
      question: z.string().describe("Уточняющий вопрос автору документа, ответ на который снимает дефект"),
    }),
  ),
});

export const ADDRESSEES = ["business", "analyst", "architect", "qa", "security"] as const;
export type Addressee = (typeof ADDRESSEES)[number];

export const QuestionsSchema = z.object({
  questions: z.array(
    z.object({
      addressee: z.enum(ADDRESSEES).describe("Кто должен ответить"),
      question: z.string().describe("Вопрос автору документа"),
      why: z.string().describe("Что нельзя реализовать или проверить без ответа"),
      options: z.array(z.string()).max(3).describe("До трёх вариантов ответа, из которых автору проще выбрать"),
      source_ids: z.array(z.string()).min(1).describe("ID находок из списка (F3, S1), из которых вырос вопрос"),
    }),
  ),
});

export type Extracted = z.infer<typeof ExtractSchema>;
export type CheckResult = z.infer<typeof CheckSchema>;
export type SetResult = z.infer<typeof SetSchema>;

/** Answers the author gave to an earlier run's questions. */
export interface Answer {
  question: string;
  answer: string;
}

const ROLE = `Ты — инженер по требованиям и проводишь статическое ревью документа с требованиями до начала разработки.
Ты не запускаешь программу и не придумываешь требования. Ты оцениваешь только то, что написано.

Общие правила:
- Пиши на русском языке.
- Цитата в находке (поле quote / quotes) — дословный фрагмент документа длиной от 3 до 30 слов, скопированный символ в символ. Не перефразируй, не склеивай разные места в одну цитату, не добавляй многоточия внутрь. Цитаты проверяются программно, неточная цитата отбрасывает находку.
- Из строки таблицы цитируй текст ячеек подряд через пробел, без символов «|» и других разделителей.
- Каждое нарушение конкретно: что именно в цитате не так и почему это мешает разработке или тестированию. Без общих фраз.
- Не выдумывай нарушений, которых нет в тексте. Но документ до ревью обычно содержит много дефектов, и пропущенный дефект дороже лишнего вопроса: проверяй каждое требование по каждому критерию по очереди.
- fix — как исправить формулировку. Не придумывай значений, которых нет в документе: вместо выдуманного числа, срока или кода пиши «[уточнить: что именно]».
- question — уточняющий вопрос автору документа, на который нужно ответить, чтобы снять дефект. Вопрос конкретный: называет цитируемое место, значение или сценарий и, если можно, предлагает варианты («Лимит 10 000 ₸ включает сумму 10 000 ₸ или только суммы выше?»). Не спрашивай «уточните требование».
- severity: high — по требованию нельзя однозначно реализовать или протестировать, либо оно противоречит другому месту; medium — существенный пробел или неоднозначность, которую придётся уточнять; low — оформление и стиль.`;

function answersBlock(answers: Answer[]): string {
  if (answers.length === 0) return "";
  return `\n\nУточнения автора документа, полученные на вопросы прошлой проверки. Считай их действующими дополнениями к документу: если ответ закрывает дефект, не сообщай о нём, если ответ сам неполон или противоречит документу, это нарушение. Цитаты в находках бери только из документа выше, не из уточнений.\n${answers
    .map((a, i) => `${i + 1}. Вопрос: ${a.question}\n   Ответ автора: ${a.answer}`)
    .join("\n")}`;
}

export function extractPrompt(docText: string): Prompt {
  return {
    system: `${ROLE}

Задача этого шага — нарезать документ на отдельные требования.
- Требование — утверждение, которое задаёт поведение, свойство, ограничение, формат данных, интерфейс или проверяемое условие системы.
- Пронумерованные пункты (например «Ф-1») бери целиком как одно требование с их номером в doc_id, даже если внутри несколько условий. Не дроби их.
- Ненумерованный текст в остальных разделах (цели, дизайн UI, нефункциональные требования, данные, интеграция, строки таблицы критериев приёмки, шаги логики метода, особые правила, параметры запроса и ответа, коды ответа) разбей на отдельные требования. Для них doc_id = null.
- Близкие строки таблицы параметров можно объединить в одно требование, если они задают одно правило.
- Строки таблицы общих параметров API, которые задают поведение (метод, авторизация, URL, описание), — отдельные требования, а не одно на всю таблицу.
- Примеры JSON-ответов и команды curl не отдельные требования: это иллюстрации к правилу или коду ответа рядом с ними.
- Не считай требованиями служебные поля шаблона: пустой чек-лист ревью, блок подписей, метаданные задачи. Пустые разделы, где должны быть требования, тоже не включай — их оценят на шаге проверки набора.
- Сохраняй порядок документа.
- Поле quote здесь — полный дословный текст требования (пункта, строки таблицы, шага), ограничение в 30 слов на него не действует.`,
    user: `Документ:\n<<<\n${docText}\n>>>`,
  };
}

export function checkPrompt(
  docText: string,
  batch: { id: string; doc_id: string | null; section: string; quote: string }[],
  answers: Answer[] = [],
): Prompt {
  return {
    system: `${ROLE}

Задача этого шага — проверить каждое требование из списка по критериям ISO/IEC/IEEE 29148:2018 п. 5.2.5 и IEEE 830-1998 п. 4.3:
${describeCriteria(INDIVIDUAL_INFO)}

Правила шага:
- Верни ровно один элемент results на каждое требование из списка, ни одного не пропускай. req_id — значение поля id из списка (например «R3»), без изменений.
- Учитывай весь документ: цели, диаграммы, критерии приёмки, дочернюю спецификацию. Термин без определения, единица измерения без пояснения, отсутствие реакции на ошибку — нарушения.
- Для одного требования может быть несколько находок по разным критериям, но не дублируй одну и ту же проблему под разными критериями.

Приёмы проверки (применяй к каждому требованию):
- Подставь граничные и недопустимые значения: что должна сделать система? Если документ не отвечает — нарушение полноты.
- Попробуй написать тест: исходное состояние, действие, ожидаемый результат, способ измерения. Если чего-то не хватает — нарушение проверяемости. Срок без точки отсчёта, способа измерения и доли запросов непроверяем.
- Ищи термины и состояния без определения, размытые слова, неясные ссылки «такой», «этот», «соответствующий».
- Сверь единицы, типы и форматы одного и того же поля во всех местах, где оно встречается (UI, данные, API, примеры).
- Для API сверь метод, коды ответа, тела ответов и описание с выполняемой операцией и между собой.
- Сверь требование с критериями приёмки и примерами: посчитай ожидаемый результат по правилу и сравни с записанным.
- Проектное решение (конкретная архитектура, хранилище, формат) внутри требования без обоснования — нарушение уместности уровня.
- Цитата находки — фрагмент самого требования или связанного с ним места документа.`,
    user: `Документ:\n<<<\n${docText}\n>>>${answersBlock(answers)}\n\nТребования для проверки:\n${JSON.stringify(batch, null, 1)}`,
  };
}

/** What code already prepared for the set step: pairs to compare and defects its rules found. */
export interface SetHints {
  pairs: [string, string][];
  foundByCode: string[];
}

export function setPrompt(
  docText: string,
  reqs: { id: string; doc_id: string | null; summary: string }[],
  answers: Answer[] = [],
  hints: SetHints = { pairs: [], foundByCode: [] },
): Prompt {
  const pairs = hints.pairs.length
    ? `\n\nПары для сверки (подобрал код по общим терминам):\n${hints.pairs.map(([a, b]) => `- ${a} и ${b}`).join("\n")}`
    : "";
  const known = hints.foundByCode.length
    ? `\n\nУже найдено кодом, не повторяй:\n${hints.foundByCode.map((x) => `- ${x}`).join("\n")}`
    : "";
  return {
    system: `${ROLE}

Задача этого шага — проверить набор требований целиком по критериям ISO/IEC/IEEE 29148:2018 п. 5.2.6 и IEEE 830-1998 п. 4.3:
${describeCriteria(SET_INFO)}

Правила шага:
- Ищи противоречия между требованиями, между требованиями и критериями приёмки, диаграммами, архитектурой и дочерним документом. Для противоречия приводи цитаты обоих мест.
- Каждый критерий приёмки проверь расчётом: примени к исходным условиям правила из требований и сравни с ожидаемым результатом. Расхождение — противоречие.
- Найди пары правил, которые срабатывают на одно и то же событие или период, и проверь, что они не требуют разного поведения.
- Сверь родительский и дочерний документы: диапазоны, типы, правила, названия операций должны совпадать.
- Проверь, какие требования не покрыты ни одним критерием приёмки (валидируемость).
- Ищи пропущенные сценарии и пустые разделы: ошибки, граничные случаи, роли, состояния, откат, безопасность, версия документа, согласование.
- Каждая находка ссылается хотя бы на одно место документа цитатой. Если речь о пустом разделе, цитируй его заголовок или заполнитель.
- req_ids — значения поля id затронутых требований из списка (например «R3»), может быть пустым для пропусков.
- Если дан список «Пары для сверки», проверь каждую пару отдельно: требуют ли два места разного поведения в одном и том же случае. Для пары с критерием приёмки посчитай ожидаемый результат по правилу из пары. Противоречие оформи находкой consistent с цитатами обоих мест. Пару без противоречия не упоминай.
- Дефекты из списка «Уже найдено кодом» в отчёте уже есть, не повторяй их.`,
    user: `Документ:\n<<<\n${docText}\n>>>${answersBlock(answers)}\n\nНарезка требований:\n${JSON.stringify(reqs, null, 1)}${pairs}${known}`,
  };
}

export interface FindingBrief {
  id: string;
  where: string;
  criterion: string;
  severity: string;
  critical: boolean;
  quote: string;
  problem: string;
  question: string;
}

export function questionsPrompt(docText: string, findings: FindingBrief[]): Prompt {
  return {
    system: `${ROLE}

Задача этого шага — составить список уточняющих вопросов автору документа по итогам ревью. Это вопросы, которые аналитик задал бы на встрече с заказчиком перед началом разработки.

Правила шага:
- На входе список находок ревью, у каждой есть id (F — находки по отдельным требованиям, S — по набору) и черновой вопрос.
- Объедини находки, на которые отвечает один и тот же ответ, в один вопрос. Не задавай один вопрос дважды.
- Один вопрос — одно решение, которое должен принять автор. Спрашивай о нужном поведении системы, а не о том, как его реализовать.
- Задавай только вопросы, на которые нужен ответ автора. Находки, которые аналитик исправит сам (оформление, нумерация, формулировка без изменения смысла), в вопросы не превращай.
- Сначала вопросы по критичным находкам (critical: true), затем остальные. Не больше 20 вопросов и ровно столько, сколько нужно: не добавляй вопросы ради числа. Находки серьёзности low без критичности пропускай, если вопросов и так больше 15.
- Вопрос конкретный и закрытый, где это возможно: называет место, значение, сценарий. Плохо: «Уточните требование Ф-3». Хорошо: «Если платёж создан менее чем за 3 дня до даты оплаты, напоминание отправляется сразу, в день оплаты или не отправляется?».
- options — разные прочтения процитированного места, каждое как конкретное поведение. Для противоречия варианты такие: как в первом месте, как во втором, оба при условии, которое нужно назвать. Если документ уже прямо называет одно прочтение, поставь его первым. Пример: «1) сразу при создании платежа; 2) в день оплаты; 3) не отправляется». Не придумывай в вариантах значений, которых нет ни в документе, ни в находке.
- why — одна фраза о том, что нельзя реализовать или проверить без ответа: что именно будет по-разному у разработчика и тестировщика при разных вариантах.
- Для addressee business формулируй вопрос без технических терминов.
- addressee — кто отвечает: business (продукт и бизнес-правила), analyst (формулировки, сценарии, критерии приёмки), architect (интеграция, API, данные, архитектура), qa (измеримость и способ проверки), security (доступ, персональные данные, безопасность).
- source_ids — id всех находок из списка, на которые отвечает вопрос, без изменений. Вопрос без source_ids не принимается.
- Не придумывай вопросов, которых нет в находках.`,
    user: `Документ:\n<<<\n${docText}\n>>>\n\nНаходки ревью:\n${JSON.stringify(findings, null, 1)}`,
  };
}
